import React from "react";
import { Html5Audio, interpolate, Sequence, staticFile } from "remotion";
import { CTA_PRESS, DURATION, END_CARD, SCENES, VOICEOVER } from "./theme";

const MUSIC_LEVEL = 0.75;
// Music drops to this share of its level while a voiceover line plays.
const VOICEOVER_DUCK = 0.38;
const DUCK_RAMP = 6;

// 0 → 1 over DUCK_RAMP frames around each voiceover line.
const speechAt = (f: number) =>
  Math.max(
    0,
    ...VOICEOVER.map(({ from, frames }) =>
      interpolate(f, [from - DUCK_RAMP, from, from + frames, from + frames + DUCK_RAMP], [0, 1, 1, 0], {
        extrapolateLeft: "clamp",
        extrapolateRight: "clamp",
      }),
    ),
  );

const musicVolume = (f: number) =>
  interpolate(f, [0, 6, DURATION - 12, DURATION], [0, 1, 1, 0], {
    extrapolateLeft: "clamp",
    extrapolateRight: "clamp",
  }) *
  MUSIC_LEVEL *
  (1 - (1 - VOICEOVER_DUCK) * speechAt(f));

// Sound effects, all generated by scripts/generate-dream-raffle-audio.mjs.
// Chimes land on the headline entrances; whooshes and the impact on the cuts.
const SFX: { file: string; from: number; volume: number }[] = [
  { file: "chime", from: 8, volume: 0.35 },
  { file: "whoosh", from: SCENES.offer.from - 5, volume: 0.8 },
  { file: "chime", from: SCENES.offer.from + 26, volume: 0.45 },
  { file: "whoosh", from: SCENES.cause.from - 6, volume: 0.45 },
  { file: "chime", from: SCENES.cause.from + 12, volume: 0.35 },
  { file: "riser", from: SCENES.cta.from - 30, volume: 0.5 },
  { file: "impact", from: SCENES.cta.from, volume: 0.7 },
  { file: "chime", from: SCENES.cta.from + 22, volume: 0.3 },
  { file: "click", from: SCENES.cta.from + CTA_PRESS, volume: 0.9 },
  { file: "chime", from: SCENES.cta.from + END_CARD + 4, volume: 0.4 },
];

export const AudioLayer: React.FC = () => (
  <>
    <Html5Audio src={staticFile("dreamraffle/audio/music.mp3")} volume={musicVolume} />
    {SFX.map(({ file, from, volume }, i) => (
      <Sequence key={i} from={from} name={`SFX: ${file}`} layout="none">
        <Html5Audio src={staticFile(`dreamraffle/audio/${file}.mp3`)} volume={volume} />
      </Sequence>
    ))}
    {VOICEOVER.map(({ file, from }) => (
      <Sequence key={file} from={from} name={`VO: ${file}`} layout="none">
        <Html5Audio src={staticFile(file)} volume={1} />
      </Sequence>
    ))}
  </>
);
