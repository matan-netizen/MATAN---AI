import React from "react";
import {
  AbsoluteFill,
  Html5Audio,
  interpolate,
  Sequence,
  staticFile,
} from "remotion";
import { SceneFade } from "./components";
import {
  SceneBenefits,
  SceneCTA,
  SceneHook,
  SceneJargon,
  SceneQuestions,
  SceneTurn,
} from "./scenes";
import { COLORS, CROSSFADE, FONT, LONG, SHORT, sfx } from "./theme";

export { FPS as DIGITAL_FPS } from "./theme";
export const DIGITAL_LONG_DURATION = LONG.duration;
export const DIGITAL_SHORT_DURATION = SHORT.duration;

type Scene = {
  name: string;
  Component: React.FC;
  from: number;
  duration: number;
};

const Timeline: React.FC<{
  scenes: Scene[];
  music: string;
  duration: number;
}> = ({ scenes, music, duration }) => (
  <AbsoluteFill
    style={{
      backgroundColor: COLORS.paper,
      direction: "rtl",
      fontFamily: FONT,
    }}
  >
    {/* Original track generated by scripts/generate-digital-audio.mjs */}
    <Html5Audio
      src={staticFile(sfx(music))}
      volume={(f) =>
        interpolate(f, [0, 6, duration - 30, duration], [0, 0.55, 0.55, 0], {
          extrapolateLeft: "clamp",
          extrapolateRight: "clamp",
        })
      }
    />
    {scenes.map(({ name, Component, from, duration: d }, i) => {
      const isLast = i === scenes.length - 1;
      // Each scene runs CROSSFADE frames into the next, which fades in on top.
      return (
        <Sequence
          key={name}
          name={name}
          from={from}
          durationInFrames={isLast ? d : d + CROSSFADE}
        >
          <SceneFade fadeIn={i > 0}>
            <Component />
          </SceneFade>
        </Sequence>
      );
    })}
  </AbsoluteFill>
);

const S = LONG.scenes;
const LONG_SCENES: Scene[] = [
  { name: "Hook", Component: SceneHook, ...S.hook },
  { name: "Questions", Component: SceneQuestions, ...S.questions },
  { name: "Jargon", Component: () => <SceneJargon />, ...S.jargon },
  { name: "Turning point", Component: () => <SceneTurn />, ...S.turn },
  { name: "Benefits", Component: SceneBenefits, ...S.benefits },
  { name: "CTA", Component: () => <SceneCTA />, ...S.cta },
];

const T = SHORT.scenes;
const SHORT_SCENES: Scene[] = [
  { name: "Jargon hook", Component: () => <SceneJargon short />, ...T.jargon },
  { name: "Wait – the offer", Component: () => <SceneTurn intro />, ...T.turn },
  { name: "CTA", Component: () => <SceneCTA short />, ...T.cta },
];

// 45s explainer: puzzled owner → questions → jargon → offer → benefits → CTA.
export const DigitalMarketing45: React.FC = () => (
  <Timeline scenes={LONG_SCENES} music="music45" duration={LONG.duration} />
);

// 15s cut for WhatsApp status / Reels: jargon hook → "רגע." → offer → CTA.
export const DigitalMarketing15: React.FC = () => (
  <Timeline scenes={SHORT_SCENES} music="music15" duration={SHORT.duration} />
);
